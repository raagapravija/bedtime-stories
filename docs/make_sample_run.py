"""Regenerate docs/sample_agent_run.md: one scripted run of the Storyteller Agent.

    python docs/make_sample_run.py

The agent is the scripted stand-in from tests/fakes.py, made to stumble on
purpose in the ways real gpt-3.5 did, so the record shows the harness at work.
"""
from __future__ import annotations

import json
import re
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT), str(ROOT / "tests")]
os.environ["BEDTIME_MEMORY"] = str(Path(tempfile.mkdtemp()) / "memory.json")

from bedtime.models import Listener, Request  # noqa: E402
from bedtime.pipeline import create_story  # noqa: E402
from fakes import (FakeLLM, agent_turn, brief_json, good_agent, judge_json, listener_json,  # noqa: E402
                   pitch_turn)


def scripted():
    """The stumbles, in order; then the competent scripted agent carries on."""
    def same_shape(m):
        turn = pitch_turn(m)
        args = json.loads(turn["tool_calls"][0]["arguments"])
        args["pitches"] = [dict(p, shape="a quest") for p in args["pitches"]]
        turn["tool_calls"][0]["arguments"] = json.dumps(args)
        return turn

    turns = [
        agent_turn("plan_story"),                                                    # plans before anything
        agent_turn("browse_ideas"),
        same_shape,                                                                  # three quests
        pitch_turn,
        agent_turn("search_library", tone="cozy"),
        agent_turn("plan_story", note="make the build-up funny"),
        agent_turn("revise_plan", part="setting", note="make it a seaside cafe"),
        agent_turn("write_part", first_event=1, last_event=2),
        agent_turn("rewrite_passage", passage=4, what_to_change="make it longer"),   # not written yet
        {"content": "Once upon a time, Mia baked a cake.", "tool_calls": []},       # types the story itself
    ]
    state = {"i": 0}

    def agent(messages):
        if state["i"] < len(turns):
            t = turns[state["i"]]
            state["i"] += 1
            return t(messages) if callable(t) else t
        return good_agent(messages)
    return agent


def short(text: str, n: int = 210) -> str:
    text = " ".join(text.split())
    return text if len(text) <= n else text[: n - 1] + "…"


def describe(call: dict) -> str:
    args = json.loads(call["function"]["arguments"])
    if "pitches" in args:
        args["pitches"] = [f'{p["title"]} ({p["shape"]})' for p in args["pitches"]]
    if "spine" in args:
        args["spine"] = f'[{3 + len(args["spine"]["because_of_that"]) + 2} beats]'
    if "events" in args:
        args["events"] = f"[{len(args['events'])} events]"
    if "characters" in args:
        args.pop("heart", None)
    return f'`{call["function"]["name"]}({", ".join(f"{k}={v!r}" for k, v in args.items())})`'


def main() -> None:
    llm = FakeLLM(classify=brief_json(), judge=[judge_json(no=4), judge_json()],
                  listener=listener_json(choice=2, why="cakes are silly and I love cake!"), agent=[scripted()])
    events: list[str] = []
    result = create_story(Listener(age=6, name="Mia"), Request("calming", ""), llm=llm, on_event=events.append)

    rows, msgs, n = [], llm.agent_messages, 0
    for i, m in enumerate(msgs[2:], 2):
        if m["role"] != "assistant":
            continue
        reply = msgs[i + 1]["content"] if i + 1 < len(msgs) else ""
        if m.get("tool_calls"):
            does = describe(m["tool_calls"][0])
        else:
            does = f"writes story text ({len((m.get('content') or '').split())} words)"
        if reply.startswith("Here is ONE example"):
            reply = reply.split("<example_story>")[0] + "… (example text) …"
        n += 1
        rows.append(f"| {n} | {does} | {short(reply).replace('|', '/')} |")

    steps = [e[2:] for e in events if e.startswith("✦ ")]
    text = f"""# Sample agent run (scripted)

This is a **test run with a scripted stand-in for gpt-3.5** (`tests/fakes.py`), regenerated by
`python docs/make_sample_run.py`. It shows the agent loop and the harness, **not** story quality: the
scripted author writes placeholder sentences. A real run's record is saved to `output/debug/*.json`.

This is the bedtime version of Agents' Room (Huot et al., ICLR 2025): the agent browses the premise
bank, pitches, lets the young listener choose, has four planning specialists (conflict, characters,
setting, plot) build the plan on a shared scratchpad, asks one specialist to revise, then has the five
section writers write the scenes. Scripted to stumble the way real gpt-3.5 did: it tries to plan before
anything, pitches three stories of the same shape, tries to edit a passage that doesn't exist yet, and
types story text itself instead of calling a tool. The young listener picks pitch 2.

| # | Agent does | Harness replies |
|---|---|---|
""" + "\n".join(rows) + """

**What the parent saw on the book's cover:**

""" + "\n".join(f"- {s}" for s in steps) + """

**Agent log** (also saved with every story):

```
""" + "\n".join(result.agent_log) + f"""
```

Result: {result.story.word_count} words, safe: {result.best.verdict.safe}, finished by the agent itself:
{result.agent_stats["finished_by_agent"]}, tool calls: {result.agent_stats["tool_calls"]}.
"""
    out = ROOT / "docs" / "sample_agent_run.md"
    out.write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
